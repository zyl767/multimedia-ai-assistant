    def detect_intent(self, query: str) -> List[str]:
        intents = []
        for intent, keywords in self.intent_keywords.items():
            for keyword in keywords:
                if keyword in query:
                    intents.append(intent)
                    break
        return intents if intents else ['通用']
    
    def extract_city(self, query: str) -> Optional[str]:
        matches = list(self.city_pattern.finditer(query))
        if not matches:
            return None
        
        if len(matches) == 1:
            return matches[0].group(1)
        
        dest_patterns = [
            r'(?:去|到|往|前往)\s*(' + '|'.join(TOURISM_KNOWLEDGE_BASE.keys()) + r')',
            r'(?:去|到|往|前往)\s*(?:旅游|玩|度假|旅行)\s*(' + '|'.join(TOURISM_KNOWLEDGE_BASE.keys()) + r')',
            r'(?:旅游|玩|度假|旅行)\s*(?:目的地|去)\s*(' + '|'.join(TOURISM_KNOWLEDGE_BASE.keys()) + r')',
        ]
        
        for pattern in dest_patterns:
            dest_match = re.search(pattern, query)
            if dest_match:
                return dest_match.group(1)
        
        for match in matches:
            city = match.group(1)
            before_text = query[:match.start()]
            if any(keyword in before_text for keyword in ['去', '到', '往', '前往', '想', '要']):
                return city
        
        return matches[-1].group(1)
    
    def extract_season(self, query: str) -> Optional[str]:
        if '寒假' in query or '春节' in query:
            return '冬季'
        if '暑假' in query:
            return '夏季'
        if '国庆' in query:
            return '秋季'
        
        match = self.season_pattern.search(query)
        if match:
            text = match.group()
            season_map = {'春': '春季', '夏': '夏季', '秋': '秋季', '冬': '冬季'}
            if text in season_map:
                return season_map[text]
        return None
    
